"""Build the candidate documents from committed outputs only.

`docs/candidates.md` and `reviewed_candidate.md` used to be written by hand, and drifted from what the pipeline had
actually produced (star counts, tiers, check counts, extinction labels). Both are now generated from files that are
in the repository:

- `registry/runs/` and `registry/samples/` (what each live search covered and flagged, with vetting tables),
- `registry/ledger.jsonl` and `registry/evidence/` (registrations and the evidence behind every check),
- `validation/certificates/` (what each channel's certificate measured, on synthetic fixtures),
- `review/records/` and the human checklists (through `oddstar.review.status`).

Every number in the generated text is read from one of those files. Commentary that is not a pipeline output lives in
`docs/notes/candidates_notes.md` and `docs/notes/reviewed_candidate_notes.md` and is included verbatim under a
heading that says so. `documents_current` (CI) rebuilds both documents and fails when the committed text differs.
"""

from __future__ import annotations

import json
import math
import re
from pathlib import Path
from typing import Any

from oddstar.registry import clean_source_id, read_ledger
from oddstar.review.status import load_review_records, review_status
from oddstar.run_records import load_run_records

CANDIDATES_DOC = "docs/candidates.md"
REVIEWED_DOC = "reviewed_candidate.md"
CANDIDATES_NOTES = "docs/notes/candidates_notes.md"
REVIEWED_NOTES = "docs/notes/reviewed_candidate_notes.md"
REGISTRATION_EVENTS = {"candidate_registered", "explained_anomaly", "tier_updated"}
TIER_ORDER = {"A": 0, "B": 1, "C": 2, "Explained": 3, "Rejected": 4}
STATUS_RANK = {"fail": 0, "not_evaluated": 1, "pass": 2}
NOTE_CHARS = 320
CERT_NAME_RE = re.compile(r"^(?P<channel>[a-z_]+)-(?P<release>dr\d+)-(?P<hash>[0-9a-f]{12})\.json$")
GENERATED_NOTICE = (
    "> Generated by `oddstar report build` from `registry/`, `validation/certificates/` and `review/`. "
    "Do not edit by hand: CI rebuilds this file and fails if it differs. Commentary goes in `{notes}`."
)


# ---------------------------------------------------------------------------------------------- formatting


def _num(v: Any) -> str:
    if v is None:
        return "n/a"
    if isinstance(v, bool):
        return "yes" if v else "no"
    if isinstance(v, int):
        return f"{v:,}"
    if isinstance(v, float):
        if not math.isfinite(v):
            return "n/a"
        if v == 0.0:
            return "0"
        a = abs(v)
        if a >= 1e5 or a < 1e-3:
            return f"{v:.3g}"
        return f"{v:.4g}"
    return str(v)


def _cell(text: Any) -> str:
    """Text safe inside a Markdown table cell."""
    return " ".join(str(text if text is not None else "").split()).replace("|", "\\|")


def _clip(text: Any, n: int = NOTE_CHARS) -> str:
    s = " ".join(str(text or "").split())
    return s if len(s) <= n else s[: n - 1] + "…"


def _table(header: list[str], rows: list[list[Any]]) -> list[str]:
    out = ["| " + " | ".join(header) + " |", "| " + " | ".join("---" for _ in header) + " |"]
    out += ["| " + " | ".join(_cell(c) for c in r) + " |" for r in rows]
    return out


def _sid(sid: str) -> str:
    return f"`Gaia DR3 {sid}`"


def _is_live(search: dict[str, Any]) -> bool:
    return any(str(c.get("cut_name", "")).endswith("_live") for c in search.get("cuts", []))


def _sample_label(search: dict[str, Any]) -> str:
    cuts = search.get("cuts") or []
    return _clip(cuts[0].get("description") or cuts[0].get("cut_name"), 110) if cuts else "n/a"


# ------------------------------------------------------------------------------------------------- loading


class Inputs:
    """Everything the documents are built from, read once."""

    def __init__(self, root: Path, registry_dir: str = "registry") -> None:
        self.root = root
        self.registry_dir = registry_dir
        self.records = load_run_records(root, registry_dir)
        self.ledger = read_ledger(root, registry_dir)
        self._samples: dict[str, set[str]] = {}
        self._review_cache: dict[str, Any] = {}

    def sample_ids(self, search: dict[str, Any]) -> set[str]:
        rel = str((search.get("sample") or {}).get("file", ""))
        if rel not in self._samples:
            p = self.root / self.registry_dir / rel
            self._samples[rel] = {str(x) for x in json.loads(p.read_text(encoding="utf-8")).get("source_ids", [])} if p.is_file() else set()
        return self._samples[rel]

    def live_searches(self) -> list[tuple[dict[str, Any], dict[str, Any]]]:
        return [(rec, s) for rec in self.records for s in rec.get("searches", []) if _is_live(s)]

    def registrations(self) -> dict[str, dict[str, Any]]:
        """Latest ledger registration with committed evidence, per source."""
        out: dict[str, dict[str, Any]] = {}
        for row in self.ledger:
            if row.get("event_type") in REGISTRATION_EVENTS and row.get("evidence_dir"):
                out[clean_source_id(str(row.get("source_id")))] = row
        return out

    def evidence(self, row: dict[str, Any]) -> dict[str, Any] | None:
        d = self.root / str(row.get("evidence_dir"))
        idx_p = d / "index.json"
        if not idx_p.is_file():
            return None
        index = json.loads(idx_p.read_text(encoding="utf-8"))
        files: dict[str, Any] = {}
        for f in index.get("files", []):
            if f.get("kind") in {"vetting", "measurement"} and (d / f["path"]).is_file():
                files[f["path"]] = json.loads((d / f["path"]).read_text(encoding="utf-8"))
        return {"dir": str(row.get("evidence_dir")), "index": index, "files": files}

    def review(self, sid: str) -> Any:
        return review_status(self.root, sid, registry_dir=self.registry_dir, _cache=self._review_cache)


def _flagged_stars(inp: Inputs) -> dict[str, dict[str, Any]]:
    """Per flagged star of the live searches: channels, runs, and its vetting merged across runs (worst status wins)."""
    out: dict[str, dict[str, Any]] = {}
    for rec, s in inp.live_searches():
        for f in s.get("flagged", []):
            sid = str(f["source_id"])
            st = out.setdefault(sid, {"channels": set(), "runs": set(), "vetting": {}, "vetted": False})
            st["channels"].add(s["channel"])
            st["runs"].add(rec["run_id"])
            rows = (s.get("vetting") or {}).get(sid)
            if rows is not None:
                st["vetted"] = True
                for v in rows:
                    cur = st["vetting"].get(v["check"])
                    if cur is None or STATUS_RANK.get(str(v["status"]), 1) < STATUS_RANK.get(str(cur["status"]), 1):
                        st["vetting"][v["check"]] = v
    return out


def _coverage(inp: Inputs) -> dict[str, Any]:
    """Distinct stars in live samples, and distinct stars actually searched per channel."""
    in_any: set[str] = set()
    per_channel: dict[str, set[str]] = {}
    for _, s in inp.live_searches():
        ids = inp.sample_ids(s)
        in_any |= ids
        searched = ids - {str(x) for x in s.get("not_searched_ids", [])}
        per_channel.setdefault(s["channel"], set()).update(searched)
    return {"n_distinct": len(in_any), "per_channel": {ch: len(v) for ch, v in sorted(per_channel.items())}}


def _certificates(root: Path) -> list[dict[str, Any]]:
    rows = []
    d = root / "validation" / "certificates"
    for p in sorted(d.glob("*.json")) if d.is_dir() else []:
        m = CERT_NAME_RE.match(p.name)
        if not m:
            continue
        c = json.loads(p.read_text(encoding="utf-8"))
        rows.append({**m.groupdict(), **{k: c.get(k) for k in (
            "passed", "blind_recovered", "blind_total", "impostors_evaluated", "impostor_max_tier",
            "injection_completeness_design_point", "false_alarm_rate", "false_alarm_ci_high")}})
    return rows


def _all_channels(root: Path) -> list[str]:
    d = root / "docs" / "channels"
    return sorted(p.stem for p in d.glob("*.md")) if d.is_dir() else []


def _notes(root: Path, rel: str) -> list[str]:
    p = root / rel
    if not p.is_file() or not p.read_text(encoding="utf-8").strip():
        return []
    return ["", "## Notes (written by hand, not pipeline output)", "", p.read_text(encoding="utf-8").strip()]


# ------------------------------------------------------------------------------------------ shared blocks


def _not_searched(s: dict[str, Any]) -> str:
    cov = s.get("coverage")
    if not cov:
        return "0"
    parts = [f"{label} {_num(cov.get(k))}" for k, label in (("n_failed", "fetch failed"), ("n_no_coverage", "no coverage"),
             ("n_insufficient_visits", "too few visits"), ("n_no_light_curve", "no light curve"),
             ("n_not_fetched", "not fetched")) if cov.get(k)]
    return f"{_num(cov.get('n_not_searched'))}" + (f" ({', '.join(parts)})" if parts else "")


def _vetting_counts(rows: list[dict[str, Any]]) -> str:
    n = {"pass": 0, "fail": 0, "not_evaluated": 0}
    for v in rows:
        n[str(v.get("status"))] = n.get(str(v.get("status")), 0) + 1
    return f"{n['pass']} pass, {n['fail']} fail, {n['not_evaluated']} not evaluated"


def _evidence_vetting(ev: dict[str, Any]) -> list[dict[str, Any]]:
    out = []
    for row in ev["index"].get("vetting", []):
        payload = ev["files"].get(row.get("evidence") or "", {})
        out.append({"check": row["check"], "status": row["status"], "note": payload.get("note", ""), "file": row.get("evidence")})
    return sorted(out, key=lambda r: (STATUS_RANK.get(str(r["status"]), 1), r["check"]))


def _measurement_lines(ev: dict[str, Any], link_prefix: str) -> list[str]:
    lines: list[str] = []
    for name, payload in sorted(ev["files"].items()):
        if not name.startswith("measurement_"):
            continue
        sc = payload.get("score") or {}
        lines.append(f"**`{payload.get('channel')}`** ([{name}]({link_prefix}{ev['dir']}/{name})): "
                     f"statistic {_num(sc.get('raw_statistic'))}, false-alarm probability {_num(sc.get('false_alarm_prob'))}, "
                     f"{'flagged' if sc.get('flagged') else 'not flagged'}. {_clip(sc.get('summary'), 400)}")
        vals = payload.get("values") or {}
        unc = payload.get("uncertainties") or {}
        scalars = [(k, v) for k, v in sorted(vals.items()) if isinstance(v, (int, float, str, bool)) or v is None]
        if scalars:
            lines.append("")
            lines += _table(["Quantity", "Value", "Uncertainty"],
                            [[f"`{k}`", _num(v), _num(unc.get(k)) if k in unc else ""] for k, v in scalars])
        caveats = payload.get("caveats") or []
        if caveats:
            lines.append("")
            lines += [f"- Caveat: {_clip(c, 400)}" for c in caveats]
        lines.append("")
    return lines


def _review_lines(inp: Inputs, sid: str, link_prefix: str) -> list[str]:
    st = inp.review(sid)
    lines = [f"Review status: {st.summary}."]
    recs = sorted((p, r) for p, r in load_review_records(inp.root) if clean_source_id(r.source_id) == sid)
    if recs:
        lines.append("Review records: " + ", ".join(
            f"[round {r.round}, {r.reviewer_model}]({link_prefix}{p.relative_to(inp.root).as_posix()})" for p, r in recs) + ".")
    if st.checklist_files:
        lines.append(f"Human checklist: {st.checklist_ticked} of {st.checklist_total} items ticked ("
                     + ", ".join(f"[{Path(f).name}]({link_prefix}{f})" for f in st.checklist_files) + ").")
    if st.open_findings:
        lines.append("Open reviewer findings: " + ", ".join(f"`{f}`" for f in st.open_findings) + ".")
    return lines


def _headline(inp: Inputs) -> list[str]:
    cov = _coverage(inp)
    flagged = _flagged_stars(inp)
    reg = inp.registrations()
    live_ids = set(flagged)
    tiers: dict[str, int] = {}
    for sid in live_ids:
        t = str(reg[sid].get("tier")) if sid in reg else "not registered"
        tiers[t] = tiers.get(t, 0) + 1
    if not inp.live_searches():
        return ["No live search has a committed run record yet (`registry/runs/` is empty), so no star count is stated here."]
    per = ", ".join(f"`{ch}` {_num(n)}" for ch, n in cov["per_channel"].items())
    tier_txt = ", ".join(f"{_num(n)} {t}" for t, n in sorted(tiers.items(), key=lambda kv: TIER_ORDER.get(kv[0], 9))) or "none"
    return [
        f"{_num(cov['n_distinct'])} distinct stars were in at least one live sample. Distinct stars actually searched, by channel: {per}.",
        f"{_num(len(flagged))} stars were flagged by at least one channel. Registered outcome of those: {tier_txt}.",
    ]


# ------------------------------------------------------------------------------------------- candidates.md


def build_candidates_md(root: Path, registry_dir: str = "registry") -> str:
    inp = Inputs(root, registry_dir)
    up = "../"
    L: list[str] = ["# `oddstar` candidates registry", "", GENERATED_NOTICE.format(notes=CANDIDATES_NOTES), ""]
    L += _headline(inp)

    # 1. searches
    L += ["", "## 1. Live searches", ""]
    live = inp.live_searches()
    if live:
        rows = []
        for rec, s in live:
            nr = s.get("null_report") or {}
            rows.append([f"[`{rec['run_id']}`]({up}{registry_dir}/runs/{rec['run_id']}.json)", _sample_label(s), f"`{s['channel']}`",
                         _num(s["sample"]["n"]), _num(s["n_searched"]), _not_searched(s), _num(s["n_flagged"]),
                         _num(nr.get("expected_false_alarms")), f"`{s.get('config_hash')}`", f"`{str(s.get('git_commit'))[:7]}`"])
        L += _table(["Run", "Sample", "Channel", "Stars in sample", "Searched", "Not searched", "Flagged", "Expected false alarms",
                     "Config", "Code"], rows)
        L += ["", "A star that was not searched is excluded from the null result of that run. "
                  "Sample membership is in `registry/samples/` (one file of source_ids per sample)."]
    else:
        L += ["No committed run record of a live search."]
    searched_live = {s["channel"] for _, s in live}
    never = [ch for ch in _all_channels(root) if ch not in searched_live]
    if never:
        L += ["", "Channels with no committed live search: " + ", ".join(f"`{c}`" for c in never)
              + ". Their certificates below come from synthetic fixtures only; nothing is claimed about the sky from them."]
    fixture_runs = [(rec, s) for rec in inp.records for s in rec.get("searches", []) if not _is_live(s)]
    if fixture_runs:
        L += ["", f"{len(fixture_runs)} committed record(s) are of fixture (synthetic) searches and are not counted above: "
              + ", ".join(f"`{rec['run_id']}`" for rec, _ in fixture_runs) + "."]

    # 2. flagged stars
    L += ["", "## 2. Flagged stars", ""]
    flagged = _flagged_stars(inp)
    reg = inp.registrations()
    if flagged:
        rows = []
        for sid, st in sorted(flagged.items(), key=lambda kv: (TIER_ORDER.get(str(reg.get(kv[0], {}).get("tier")), 9), kv[0])):
            vrows = list(st["vetting"].values())
            fails = sorted(v["check"] for v in vrows if v["status"] == "fail")
            r = reg.get(sid)
            rows.append([_sid(sid), ", ".join(f"`{c}`" for c in sorted(st["channels"])),
                         _vetting_counts(vrows) if st["vetted"] else "not vetted",
                         ", ".join(f"`{c}`" for c in fails) or "none",
                         f"**{r['tier']}**" if r else "not registered",
                         f"[evidence]({up}{r['evidence_dir']}/index.json)" if r else ""])
        L += _table(["Star", "Flagged by", "Vetting (all runs merged, worst status per check)", "Failed checks", "Registered tier", "Evidence"], rows)
    else:
        L += ["No star is flagged in a committed live run record."]

    # 3. registered candidates above Rejected
    L += ["", "## 3. Registered candidates above Rejected", ""]
    kept = sorted(((sid, r) for sid, r in reg.items() if r.get("tier") in {"A", "B", "C", "Explained"}),
                  key=lambda kv: (TIER_ORDER[str(kv[1]["tier"])], kv[0]))
    if not kept:
        L += ["No registration with committed evidence is at Tier A, B, C or Explained.", ""]
    for sid, r in kept:
        ev = inp.evidence(r)
        L += [f"### {_sid(sid)}: Tier {r['tier']}", ""]
        det = r.get("details") or {}
        if ev is None:
            L += [f"Evidence directory `{r.get('evidence_dir')}` is missing its index.", ""]
            continue
        idx = ev["index"]
        L += [f"Registered {str(r.get('timestamp_utc'))[:10]} from run `{idx.get('run_id')}` (config `{idx.get('config_hash')}`, "
              f"code `{str(idx.get('git_commit'))[:7]}`). Flagged by " + (", ".join(f"`{c}`" for c in idx.get("flagged_channels", [])) or "no channel")
              + f". Evidence: [{ev['dir']}]({up}{ev['dir']}/index.json)."]
        if det.get("explained_reason"):
            L += [f"Explained as: {_clip(det['explained_reason'], 500)}"]
        L += [""] + _review_lines(inp, sid, up) + ["", "#### Measurements", ""] + _measurement_lines(ev, up)
        vet = _evidence_vetting(ev)
        L += [f"#### Vetting: {_vetting_counts(vet)}", ""]
        L += _table(["Check", "Status", "What the check found", "Evidence"],
                    [[f"`{v['check']}`", v["status"], _clip(v["note"]), f"[{v['file']}]({up}{ev['dir']}/{v['file']})" if v["file"] else ""] for v in vet])
        holes = [v for v in vet if v["status"] == "not_evaluated"]
        if holes:
            L += ["", "Not ruled out (each `not_evaluated` check is an open hole, never a pass): "
                  + ", ".join(f"`{v['check']}`" for v in holes) + "."]
        L += [""]

    # 4. rejected with evidence
    rej = sorted((sid, r) for sid, r in reg.items() if r.get("tier") == "Rejected")
    L += ["## 4. Rejected registrations with committed evidence", ""]
    if rej:
        rows = []
        for sid, r in rej:
            ev = inp.evidence(r)
            vet = _evidence_vetting(ev) if ev else []
            rows.append([_sid(sid), f"`{(ev or {}).get('index', {}).get('run_id', 'n/a')}`",
                         "; ".join(f"`{v['check']}`: {_clip(v['note'], 160)}" for v in vet if v["status"] == "fail") or "n/a",
                         f"[evidence]({up}{r['evidence_dir']}/index.json)"])
        L += _table(["Star", "Run", "Failing check(s) that caused the rejection", "Evidence"], rows)
    else:
        L += ["None."]

    # 5. certificates
    L += ["", "## 5. Validation certificates", "",
          "Each certificate records four tests run on **synthetic fixtures**: known objects hidden in a generated field sample, "
          "known impostors, injected signals, and a false-alarm count. They show the code path works; they are not a measurement on the live sky.", ""]
    certs = _certificates(root)
    if certs:
        L += _table(["Channel", "Release", "Config", "Passed", "Known objects recovered", "Impostors (worst tier reached)",
                     "Injection completeness at design point", "False-alarm rate (95% upper bound)"],
                    [[f"`{c['channel']}`", c["release"], f"`{c['hash']}`", _num(c["passed"]), f"{_num(c['blind_recovered'])} of {_num(c['blind_total'])}",
                      f"{_num(c['impostors_evaluated'])} ({c['impostor_max_tier']})", _num(c["injection_completeness_design_point"]),
                      f"{_num(c['false_alarm_rate'])} ({_num(c['false_alarm_ci_high'])})"] for c in certs])
    else:
        L += ["No certificate files."]

    # 6. ledger
    L += ["", "## 6. Ledger", ""]
    counts: dict[str, int] = {}
    for row in inp.ledger:
        counts[str(row.get("event_type"))] = counts.get(str(row.get("event_type")), 0) + 1
    n_reg = sum(1 for row in inp.ledger if row.get("event_type") in REGISTRATION_EVENTS)
    n_ev = sum(1 for row in inp.ledger if row.get("event_type") in REGISTRATION_EVENTS and row.get("evidence_dir"))
    L += [f"`{registry_dir}/ledger.jsonl` holds {_num(len(inp.ledger))} entries: "
          + ", ".join(f"{_num(n)} `{k}`" for k, n in sorted(counts.items())) + ".",
          f"Of {_num(n_reg)} registrations, {_num(n_ev)} carry committed evidence and {_num(n_reg - n_ev)} are `legacy_without_evidence`: "
          "they were written before the evidence store existed, the evidence behind their pass rows is not in the repository, "
          "and no statement in this document rests on them."]
    L += _notes(root, CANDIDATES_NOTES)
    return "\n".join(L).rstrip() + "\n"


# ------------------------------------------------------------------------------------ reviewed_candidate.md


def build_reviewed_md(root: Path, registry_dir: str = "registry") -> str:
    inp = Inputs(root, registry_dir)
    L: list[str] = ["# Reviewed surviving candidates", "", GENERATED_NOTICE.format(notes=REVIEWED_NOTES), ""]
    L += _headline(inp)
    reg = inp.registrations()
    kept = sorted(((sid, r) for sid, r in reg.items() if r.get("tier") in {"A", "B", "C"}),
                  key=lambda kv: (TIER_ORDER[str(kv[1]["tier"])], kv[0]))
    if not kept:
        L += ["", "No star is registered at Tier A, B or C with committed evidence."]
    else:
        L += ["", f"{_num(len(kept))} star(s) are registered at Tier A, B or C with committed evidence. "
                  f"The full tables are in [{CANDIDATES_DOC}]({CANDIDATES_DOC})."]
    for sid, r in kept:
        ev = inp.evidence(r)
        L += ["", f"## {_sid(sid)}: Tier {r['tier']}", ""]
        if ev is None:
            L += [f"Evidence directory `{r.get('evidence_dir')}` is missing its index."]
            continue
        idx = ev["index"]
        vet = _evidence_vetting(ev)
        L += _table(["Field", "Value"], [
            ["Tier", f"**{r['tier']}**"],
            ["Flagged by", ", ".join(f"`{c}`" for c in idx.get("flagged_channels", [])) or "no channel"],
            ["Vetting", _vetting_counts(vet)],
            ["Run / config / code", f"`{idx.get('run_id')}` / `{idx.get('config_hash')}` / `{str(idx.get('git_commit'))[:7]}`"],
            ["Evidence", f"[{ev['dir']}]({ev['dir']}/index.json)"],
            ["Review", inp.review(sid).summary],
        ])
        L += [""] + _review_lines(inp, sid, "")[1:]
        L += ["", "### What the channels measured", ""] + _measurement_lines(ev, "")
        fails = [v for v in vet if v["status"] == "fail"]
        holes = [v for v in vet if v["status"] == "not_evaluated"]
        L += ["### What is not ruled out", ""]
        if holes:
            L += [f"- `{v['check']}`: {_clip(v['note'], 500)}" for v in holes]
        else:
            L += ["Every applicable check was evaluated."]
        if fails:
            L += ["", "### Checks that failed", ""] + [f"- `{v['check']}`: {_clip(v['note'], 500)}" for v in fails]
        L += ["", "### Checks that passed", "", ", ".join(f"`{v['check']}`" for v in vet if v["status"] == "pass") or "none"]
    L += _notes(root, REVIEWED_NOTES)
    return "\n".join(L).rstrip() + "\n"


# -------------------------------------------------------------------------------------------- build / check


def build_documents(root: Path, registry_dir: str = "registry") -> dict[str, str]:
    """Relative path -> generated text of every generated document."""
    return {CANDIDATES_DOC: build_candidates_md(root, registry_dir), REVIEWED_DOC: build_reviewed_md(root, registry_dir)}


def write_documents(root: Path, registry_dir: str = "registry") -> list[str]:
    """Write the generated documents; returns the relative paths whose content changed."""
    changed = []
    for rel, text in build_documents(root, registry_dir).items():
        p = root / rel
        if not p.exists() or p.read_text(encoding="utf-8") != text:
            p.parent.mkdir(parents=True, exist_ok=True)
            p.write_text(text, encoding="utf-8")
            changed.append(rel)
    return changed


def stale_documents(root: Path, registry_dir: str = "registry") -> list[str]:
    """Generated documents whose committed text differs from a fresh build."""
    out = []
    for rel, text in build_documents(root, registry_dir).items():
        p = root / rel
        if not p.exists() or p.read_text(encoding="utf-8") != text:
            out.append(rel)
    return out
